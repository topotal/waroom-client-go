//go:embed templates/*.tmpl
var templateFS embed.FS

const header = "// Code generated by genwaroom. DO NOT EDIT."

// serviceView augments the semantic Service with the names derived from
// its tag and the render-time Go source fragments the templates stamp
// verbatim.
type serviceView struct {
	*Service
	Name     string // LabelService
	Accessor string // Labels
	FileName string // labels_gen.go
	Ops      []*opView
}

type opView struct {
	*Op
	GoName      string // effective public method name (Op.GoName or RawName)
	ParamsDecl  string // "ctx context.Context, name string, req CreateServiceLabelRequest"
	ResultsDecl string // "(*CreatedLabel, error)"
	ZeroRet     string // "nil, " for value+error results, "" for error-only
	RawArgs     string // arguments passed to s.client.raw.<RawName>(...)
	FwdArgs     string // arguments the All iterator forwards ("ctx, name, o")
	ErrCases    []errCaseView
}

type errCaseView struct {
	Variant string
	Status  int
}

// buildServiceView derives all Go fragments from the semantic model. This
// is the only place that turns model shapes into source text.
func buildServiceView(svc *Service) (*serviceView, error) {
	view := &serviceView{
		Service:  svc,
		Name:     serviceName(svc.Tag),
		Accessor: serviceAccessor(svc.Tag),
		FileName: serviceFileName(svc.Tag),
	}
	for _, op := range svc.Ops {
		ov, err := buildOpView(op)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", op.ID, err)
		}
		view.Ops = append(view.Ops, ov)
	}
	return view, nil
}

func buildOpView(op *Op) (*opView, error) {
	v := &opView{Op: op, GoName: op.RawName}
	if op.GoName != "" {
		v.GoName = op.GoName
	}

	// Public parameter list: ctx, path args, req, opts.
	decl := []string{"ctx context.Context"}
	for _, p := range op.PathParams {
		decl = append(decl, lowerCamel(p.GenField)+" "+p.Type)
	}
	if op.Request != nil {
		decl = append(decl, "req "+op.Request.Public)
	}
	if op.Options != nil {
		decl = append(decl, "opts "+op.Options.Name)
	}
	v.ParamsDecl = strings.Join(decl, ", ")

	// Raw call arguments: ctx, request expression, params literal.
	args := []string{"ctx"}
	if op.Request != nil {
		if op.Request.UnwrapField != "" {
			args = append(args, fmt.Sprintf("&gen.%s{%s: req}", op.Request.Gen, op.Request.UnwrapField))
		} else {
			args = append(args, "&req")
		}
	}
	if op.ParamsGen != "" {
		var inits []string
		for _, p := range op.PathParams {
			inits = append(inits, p.GenField+": "+lowerCamel(p.GenField))
		}
		if op.Options != nil {
			for _, f := range op.Options.Fields {
				inits = append(inits, f.Name+": opts."+f.Name)
			}
		}
		args = append(args, fmt.Sprintf("gen.%s{%s}", op.ParamsGen, strings.Join(inits, ", ")))
	}
	v.RawArgs = strings.Join(args, ", ")

	switch op.Success.Kind {
	case "none":
		v.ResultsDecl, v.ZeroRet = "error", ""
	case "list":
		v.ResultsDecl, v.ZeroRet = "(*"+op.Success.ListName+", error)", "nil, "
	case "unwrap", "whole":
		v.ResultsDecl, v.ZeroRet = "(*"+op.Success.Public+", error)", "nil, "
	default:
		return nil, fmt.Errorf("unknown success kind %q", op.Success.Kind)
	}

	if op.All {
		fwd := []string{"ctx"}
		for _, p := range op.PathParams {
			fwd = append(fwd, lowerCamel(p.GenField))
		}
		fwd = append(fwd, "o")
		v.FwdArgs = strings.Join(fwd, ", ")
	}

	for _, variant := range op.Errors {
		status, err := statusOf(variant, op.RawName)
		if err != nil {
			return nil, err
		}
		v.ErrCases = append(v.ErrCases, errCaseView{Variant: variant, Status: status})
	}
	return v, nil
}

// render writes the generated files into outDir, removing genwaroom files
// from previous runs so renames don't leave stale output behind.
func render(model *Model, outDir string) error {
	tmpl, err := template.ParseFS(templateFS, "templates/*.tmpl")
	if err != nil {
		return err
	}

	if err := removeStale(outDir); err != nil {
		return err
	}

	var views []*serviceView
	for _, svc := range model.Services {
		view, err := buildServiceView(svc)
		if err != nil {
			return err
		}
		views = append(views, view)
		if err := renderFile(tmpl, "service.tmpl", view, filepath.Join(outDir, view.FileName)); err != nil {
			return err
		}
	}
	client := struct{ Services []*serviceView }{Services: views}
	if err := renderFile(tmpl, "client.tmpl", client, filepath.Join(outDir, "client_gen.go")); err != nil {
		return err
	}
	return renderFile(tmpl, "types.tmpl", model.Types, filepath.Join(outDir, "types_gen.go"))
}

func renderFile(tmpl *template.Template, name string, data any, path string) error {
	var buf bytes.Buffer
	if err := tmpl.ExecuteTemplate(&buf, name, data); err != nil {
		return fmt.Errorf("render %s: %w", path, err)
	}
	src, err := imports.Process(path, buf.Bytes(), nil)
	if err != nil {
		return fmt.Errorf("format %s: %w (raw output:\n%s)", path, err, buf.String())
	}
	return os.WriteFile(path, src, 0o644)
}

// removeStale deletes previously generated *_gen.go files (identified by
// the genwaroom header) from outDir.
func removeStale(outDir string) error {
	matches, err := filepath.Glob(filepath.Join(outDir, "*_gen.go"))
	if err != nil {
		return err
	}
	for _, path := range matches {
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if strings.HasPrefix(string(data), header) {
			if err := os.Remove(path); err != nil {
				return err
			}
		}
	}
	return nil
}
