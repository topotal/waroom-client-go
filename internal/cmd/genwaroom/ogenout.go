package main

import (
	"os"
	"path/filepath"
	"strings"

	"github.com/ogen-go/ogen/gen"
)

const ogenHeader = "// Code generated by ogen, DO NOT EDIT."

type dirFS struct{ dir string }

func (d dirFS) WriteFile(baseName string, source []byte) error {
	return os.WriteFile(filepath.Join(d.dir, baseName), source, 0o644)
}

// writeOgen writes the low-level client into target from the same
// Generator instance the model was derived from, replacing files from
// previous runs (the equivalent of `ogen --clean`).
func writeOgen(g *gen.Generator, target string) error {
	matches, err := filepath.Glob(filepath.Join(target, "*.go"))
	if err != nil {
		return err
	}
	for _, path := range matches {
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if strings.HasPrefix(string(data), ogenHeader) {
			if err := os.Remove(path); err != nil {
				return err
			}
		}
	}
	if err := os.MkdirAll(target, 0o755); err != nil {
		return err
	}
	return g.WriteSource(dirFS{dir: target}, "ogen")
}
