package main

import (
	"fmt"
	"os"

	"github.com/go-faster/yaml"
)

const modelHeader = `# Code generated by "genwaroom analyze" from internal/ogen. DO NOT EDIT.
#
# This is the derived intermediate model of the public SDK surface. Review
# its diff to see how spec/ogen changes affect the generated API. To
# influence it, edit .genwaroom.yaml (include/skip/groups/rename) and run
# "task gen" — never edit this file by hand.
`

// writeModel serializes the semantic model to YAML.
func writeModel(path string, model *Model) error {
	data, err := yaml.Marshal(model)
	if err != nil {
		return err
	}
	return os.WriteFile(path, append([]byte(modelHeader), data...), 0o644)
}

// readModel deserializes the semantic model from YAML.
func readModel(path string) (*Model, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	model := &Model{}
	if err := yaml.Unmarshal(data, model); err != nil {
		return nil, fmt.Errorf("parse %s: %w", path, err)
	}
	return model, nil
}
