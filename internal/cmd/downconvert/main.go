// Command downconvert converts an OpenAPI 3.1 document to OpenAPI 3.0
// so that it can be consumed by ogen, which does not support 3.1.
//
// It only handles the 3.1 features actually used by the Waroom API spec:
// type arrays with "null" (e.g. `type: [integer, "null"]`) are rewritten
// to the 3.0 form (`type: integer` + `nullable: true`). Any other
// non-convertible construct results in an error.
package main

import (
	"flag"
	"fmt"
	"log"
	"os"

	"github.com/go-faster/yaml"
)

func main() {
	in := flag.String("in", "api/openapi.yaml", "input OpenAPI 3.1 file")
	out := flag.String("out", "api/openapi-3.0.yaml", "output OpenAPI 3.0 file")
	flag.Parse()

	src, err := os.ReadFile(*in)
	if err != nil {
		log.Fatal(err)
	}

	var doc yaml.Node
	if err := yaml.Unmarshal(src, &doc); err != nil {
		log.Fatal(err)
	}

	root := doc.Content[0]
	if err := setVersion(root); err != nil {
		log.Fatal(err)
	}
	if err := convert(root); err != nil {
		log.Fatal(err)
	}

	buf, err := yaml.Marshal(root)
	if err != nil {
		log.Fatal(err)
	}
	header := []byte("# Code generated by internal/cmd/downconvert from " + *in + "; DO NOT EDIT.\n")
	if err := os.WriteFile(*out, append(header, buf...), 0o644); err != nil {
		log.Fatal(err)
	}
}

func setVersion(root *yaml.Node) error {
	for i := 0; i < len(root.Content); i += 2 {
		if root.Content[i].Value == "openapi" {
			root.Content[i+1].Value = "3.0.3"
			return nil
		}
	}
	return fmt.Errorf("no openapi version field found")
}

// convert walks the YAML tree and rewrites 3.1 nullable type arrays
// into the 3.0 `nullable: true` form.
func convert(n *yaml.Node) error {
	if n.Kind == yaml.MappingNode {
		for i := 0; i < len(n.Content); i += 2 {
			k, v := n.Content[i], n.Content[i+1]
			if k.Value == "type" && v.Kind == yaml.SequenceNode {
				if err := rewriteTypeArray(n, i, v); err != nil {
					return err
				}
				continue
			}
			if err := convert(v); err != nil {
				return err
			}
		}
		return nil
	}
	for _, c := range n.Content {
		if err := convert(c); err != nil {
			return err
		}
	}
	return nil
}

// rewriteTypeArray replaces the type array at m.Content[i+1] with a scalar
// type, appending `nullable: true` when the array contained "null".
func rewriteTypeArray(m *yaml.Node, i int, types *yaml.Node) error {
	var concrete []string
	nullable := false
	for _, t := range types.Content {
		if t.Value == "null" {
			nullable = true
		} else {
			concrete = append(concrete, t.Value)
		}
	}
	if len(concrete) != 1 {
		return fmt.Errorf("line %d: type array %v is not representable in OpenAPI 3.0", types.Line, concrete)
	}
	m.Content[i+1] = &yaml.Node{Kind: yaml.ScalarNode, Value: concrete[0]}
	if nullable {
		m.Content = append(m.Content,
			&yaml.Node{Kind: yaml.ScalarNode, Value: "nullable"},
			&yaml.Node{Kind: yaml.ScalarNode, Value: "true", Tag: "!!bool"},
		)
	}
	return nil
}
