// Command specversion writes the OpenAPI spec's info.version as a Go constant,
// so the SDK can report which spec version it was generated from.
//
// Usage: go run ./internal/cmd/specversion <openapi.yaml> <output.go>
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"

	"gopkg.in/yaml.v3"
)

func main() {
	if len(os.Args) != 3 {
		log.Fatal("usage: specversion <openapi.yaml> <output.go>")
	}
	if err := run(os.Args[1], os.Args[2]); err != nil {
		log.Fatal(err)
	}
}

func run(specPath, outPath string) error {
	b, err := os.ReadFile(specPath)
	if err != nil {
		return err
	}
	version, err := specVersion(b)
	if err != nil {
		return fmt.Errorf("%s: %w", specPath, err)
	}
	src, err := render(version)
	if err != nil {
		return err
	}
	return os.WriteFile(outPath, src, 0o644)
}

func specVersion(spec []byte) (string, error) {
	var doc struct {
		Info struct {
			Version string `yaml:"version"`
		} `yaml:"info"`
	}
	if err := yaml.Unmarshal(spec, &doc); err != nil {
		return "", err
	}
	if doc.Info.Version == "" {
		return "", fmt.Errorf("info.version is empty")
	}
	return doc.Info.Version, nil
}

func render(version string) ([]byte, error) {
	var buf bytes.Buffer
	fmt.Fprintf(&buf, `// Code generated by internal/cmd/specversion, DO NOT EDIT.

package ogen

// SpecVersion is info.version of the OpenAPI spec this package was generated from.
const SpecVersion = %q
`, version)
	return format.Source(buf.Bytes())
}
