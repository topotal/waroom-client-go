package main

import (
	"bytes"
	_ "embed"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"
)

type spec struct {
	Types        []string        `yaml:"types"`
	Constructors []constructorEl `yaml:"constructors"`
}

type constructorEl struct {
	Name string `yaml:"name"`
	Type string `yaml:"type"`
}

func (c *constructorEl) UnmarshalYAML(value *yaml.Node) error {
	// サポート形式： "NewOptString" or {name: NewOptTime, type: time.Time}
	var s string
	if err := value.Decode(&s); err == nil {
		c.Name = s
		c.Type = inferTypeFromName(s)
		return nil
	}
	var aux struct{ Name, Type string }
	if err := value.Decode(&aux); err != nil {
		return err
	}
	if aux.Name == "" {
		return errors.New("constructor.name is required")
	}
	c.Name = aux.Name
	c.Type = aux.Type
	if c.Type == "" {
		c.Type = inferTypeFromName(c.Name)
	}
	return nil
}

func inferTypeFromName(name string) string {
	s := strings.ToLower(name)
	switch {
	case strings.Contains(s, "string"):
		return "string"
	case strings.Contains(s, "bool"):
		return "bool"
	case strings.Contains(s, "int64"):
		return "int64"
	case strings.Contains(s, "int32"):
		return "int32"
	case strings.Contains(s, "int"):
		return "int"
	case strings.Contains(s, "float64"):
		return "float64"
	case strings.Contains(s, "float32"):
		return "float32"
	case strings.Contains(s, "time"):
		return "time.Time"
	default:
		return "interface{}" // 最低限。必要なら expose.yaml で type を明示
	}
}

func main() {
	var (
		apiImport = flag.String("api-import", "github.com/topotal/waroom-client-go/internal/ogen", "import path for generated api package (e.g. github.com/topotal/waroom-client-go/internal/ogen)")
		exposeY   = flag.String("expose", "expose.yaml", "path to expose.yaml")
		outPath   = flag.String("out", "waroom/types.go", "output file (e.g. waroom/types.gen.go)")
		pkgName   = flag.String("pkg", "waroom", "package name for the generated file")
	)
	flag.Parse()

	if *apiImport == "" || *exposeY == "" || *outPath == "" {
		fmt.Fprintf(os.Stderr, "usage: gentypes -api_import <import> -expose waroom/expose.yaml -out waroom/types.gen.go\n")
		os.Exit(2)
	}

	b, err := os.ReadFile(*exposeY)
	if err != nil {
		fatal(err)
	}
	var sp spec
	if err := yaml.Unmarshal(b, &sp); err != nil {
		fatal(err)
	}

	// 重複除去＆安定ソート
	dedup := func(ss []string) []string {
		m := map[string]struct{}{}
		out := make([]string, 0, len(ss))
		for _, s := range ss {
			if _, ok := m[s]; !ok {
				m[s] = struct{}{}
				out = append(out, s)
			}
		}
		sort.Strings(out)
		return out
	}
	sp.Types = dedup(sp.Types)
	sort.SliceStable(sp.Constructors, func(i, j int) bool { return sp.Constructors[i].Name < sp.Constructors[j].Name })

	var needsTime bool
	for _, c := range sp.Constructors {
		if c.Type == "time.Time" {
			needsTime = true
			break
		}
	}

	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by cmd/gentypes; DO NOT EDIT.\n")
	fmt.Fprintf(&buf, "package %s\n\n", *pkgName)
	fmt.Fprintf(&buf, "import (\n")
	fmt.Fprintf(&buf, "\tgen \"%s\"\n", *apiImport)
	if needsTime {
		fmt.Fprintf(&buf, "\t\"time\"\n")
	}
	fmt.Fprintf(&buf, ")\n\n")

	// type alias block
	if len(sp.Types) > 0 {
		fmt.Fprintf(&buf, "type (\n")
		for _, t := range sp.Types {
			fmt.Fprintf(&buf, "\t%[1]s = gen.%[1]s\n", t)
		}
		fmt.Fprintf(&buf, ")\n\n")
	}

	// forward constructors
	for _, c := range sp.Constructors {
		if c.Type == "" {
			c.Type = "interface{}"
		}
		fmt.Fprintf(&buf, "func %s(v %s) %s { return gen.%s(v) }\n", c.Name, c.Type, strings.TrimPrefix(c.Name, "New"), c.Name)
	}

	// format
	src, err := format.Source(buf.Bytes())
	if err != nil {
		fatal(err)
	}

	if err := os.MkdirAll(filepath.Dir(*outPath), 0o755); err != nil {
		fatal(err)
	}
	if err := os.WriteFile(*outPath, src, 0o644); err != nil {
		fatal(err)
	}
}

func fatal(err error) { fmt.Fprintln(os.Stderr, err); os.Exit(1) }
